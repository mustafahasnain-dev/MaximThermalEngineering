// Page report and placeholder register.
// 1. Reads dist/ and prints URL, title and own-content word count per page (shared contact block excluded).
// 2. Scans the source (content, data, components) and writes PLACEHOLDERS.md: every [placeholder] and
//    [verify] marker with the page it belongs to, the file and line, and the line's text for context.
import fs from 'node:fs';
import path from 'node:path';

const DIST = path.resolve('dist');
const walk = (dir, ext) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p, ext) : ext.some((x) => e.name.endsWith(x)) ? [p] : [];
  });
const decode = (s) => s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&rsaquo;/g, '›').replace(/&nbsp;/g, ' ');
const text = (html) => decode(html.replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ').replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();
const posix = (p) => p.split(path.sep).join('/');

// ---- 1. Page report
const rows = walk(DIST, ['.html'])
  .map((file) => {
    const html = fs.readFileSync(file, 'utf8');
    const url = '/' + posix(path.relative(DIST, file)).replace(/index\.html$/, '');
    const title = decode(html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] ?? '');
    const main = html.match(/<main[\s\S]*?<\/main>/i)?.[0] ?? '';
    const own = main.replace(/<section id="contact"[\s\S]*?<\/section>/i, '');
    return { url, title, words: text(own).split(' ').filter(Boolean).length };
  })
  .sort((a, b) => a.url.localeCompare(b.url));

const only = process.argv[2]; // optional URL prefix, e.g. /services/
const shown = only ? rows.filter((r) => r.url.startsWith(only)) : rows;
console.log('| URL | Title | Words |\n|---|---|---|');
for (const r of shown) console.log(`| ${r.url} | ${r.title} | ${r.words} |`);

// ---- 2. Placeholder register from source
const pageFor = (file) => {
  const rel = posix(path.relative('src', file));
  let m;
  if ((m = rel.match(/^content\/services\/(.+)\.md$/))) return `/services/${m[1]}/`;
  if ((m = rel.match(/^content\/(cities|industries|projects|articles|glossary)\/(.+)\.mdx?$/))) {
    const base = { cities: 'locations', industries: 'industries', projects: 'projects', articles: 'learn', glossary: 'glossary' }[m[1]];
    return `/${base}/${m[2]}/`;
  }
  if (/^(data\/home\.ts|components\/home\/)/.test(rel)) return '/';
  return `shared (${rel})`;
};
const clean = (line) =>
  line.trim().replace(/^-\s*/, '').replace(/^[a-zA-Z]+:\s*/, '').replace(/^["']|["'],?$/g, '').replace(/\s+/g, ' ').slice(0, 260);

const groups = new Map();
let counts = { placeholder: 0, verify: 0 };
for (const file of walk('src', ['.md', '.mdx', '.ts', '.astro', '.json'])) {
  if (file.includes(`${path.sep}schemas.ts`)) continue;
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  lines.forEach((line, i) => {
    const found = line.match(/\[(placeholder|verify)[^\]]*\]/gi);
    if (!found) return;
    const page = pageFor(file);
    if (!groups.has(page)) groups.set(page, []);
    for (const mk of found) {
      const kind = /^\[verify/i.test(mk) ? 'verify' : 'placeholder';
      counts[kind]++;
      groups.get(page).push({ kind, marker: mk, where: `${posix(path.relative('.', file))}:${i + 1}`, context: clean(line) });
    }
  });
}

let md = '# Placeholders and items to verify\n\nGenerated by `npm run report` from the source files. Do not edit by hand; fix the source and re-run.\n\n';
md += '- **[placeholder]**: real content or data needed from Maxim Thermal.\n- **[verify]**: a statement an engineer must confirm before launch.\n\n';
md += `Totals: ${counts.placeholder} placeholders, ${counts.verify} items to verify.\n\n`;
const order = [...groups.keys()].sort((a, b) => (a.startsWith('shared') ? 1 : 0) - (b.startsWith('shared') ? 1 : 0) || a.localeCompare(b));
for (const page of order) {
  const items = groups.get(page);
  md += `## ${page}\n\n`;
  for (const kind of ['placeholder', 'verify']) {
    const list = items.filter((x) => x.kind === kind);
    if (!list.length) continue;
    md += `**${kind === 'placeholder' ? 'Placeholders' : 'To verify'}**\n\n`;
    for (const x of list) md += `- \`${x.where}\`: ${x.context}\n`;
    md += '\n';
  }
}
fs.writeFileSync('PLACEHOLDERS.md', md);
console.log(`\n${shown.length} pages · ${counts.placeholder} [placeholder] · ${counts.verify} [verify] markers in source · wrote PLACEHOLDERS.md`);
